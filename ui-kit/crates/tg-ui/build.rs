//! Embeds the icons: the IntelliJ SVGs `scripts/extract-icons.py` copied into `assets/icons/intellij` (listed in its
//! `manifest.json`), and TableGrip's own icons straight from the Kotlin app's resources.

use std::fmt::Write;
use std::path::{Path, PathBuf};

fn main() {
    let crate_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let intellij = crate_dir.join("assets/icons/intellij");
    let app_icons = crate_dir.join("../../../app/src/main/resources/icons");
    let manifest = intellij.join("manifest.json");
    println!("cargo:rerun-if-changed={}", manifest.display());
    println!("cargo:rerun-if-changed={}", app_icons.display());

    let json: serde_json::Value =
        serde_json::from_str(&std::fs::read_to_string(&manifest).unwrap()).unwrap();
    let mut assets = Vec::<(String, PathBuf)>::new();
    let mut keys = std::collections::BTreeMap::<String, (Option<String>, Option<String>)>::new();
    for icon in json["icons"].as_array().unwrap() {
        let file = icon["file"].as_str().unwrap();
        let path = format!("icons/intellij/{file}");
        assets.push((path.clone(), intellij.join(file)));
        let entry = keys
            .entry(icon["key"].as_str().unwrap().to_owned())
            .or_default();
        if icon["dark"].as_bool().unwrap() {
            entry.1 = Some(path);
        } else {
            entry.0 = Some(path);
        }
    }
    // TableGrip's own icons: `<name>.svg` and `<name>_dark.svg`, keyed `TableGrip.<Name>`.
    let mut own: Vec<PathBuf> = std::fs::read_dir(&app_icons)
        .unwrap()
        .map(|e| e.unwrap().path())
        .filter(|p| p.extension().is_some_and(|e| e == "svg"))
        .collect();
    own.sort();
    for path in own {
        let stem = path.file_stem().unwrap().to_string_lossy().into_owned();
        let asset = format!("icons/{stem}.svg");
        assets.push((asset.clone(), path.clone()));
        let (base, dark) = match stem.strip_suffix("_dark") {
            Some(base) => (base.to_owned(), true),
            None => (stem.clone(), false),
        };
        let key = format!("TableGrip.{}{}", base[..1].to_uppercase(), &base[1..]);
        let entry = keys.entry(key).or_default();
        if dark {
            entry.1 = Some(asset);
        } else {
            entry.0 = Some(asset);
        }
    }

    let mut out =
        String::from("// Generated by build.rs.\n\npub static ASSETS: &[(&str, &[u8])] = &[\n");
    for (name, path) in &assets {
        writeln!(
            out,
            "    ({name:?}, include_bytes!({:?})),",
            canonical(path)
        )
        .unwrap();
    }
    out.push_str("];\n\n/// (key, light file, dark file)\npub static KEYS: &[(&str, &str, Option<&str>)] = &[\n");
    for (key, (light, dark)) in &keys {
        let light = light
            .as_ref()
            .unwrap_or_else(|| panic!("{key} has no light variant"));
        writeln!(out, "    ({key:?}, {light:?}, {dark:?}),").unwrap();
    }
    out.push_str("];\n");
    let dest = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("icons.rs");
    std::fs::write(dest, out).unwrap();
}

/// [path] as `include_bytes!` takes it; not canonicalised, which on Windows would give a `\\?\` path.
fn canonical(path: &Path) -> String {
    assert!(path.is_file(), "{} is missing", path.display());
    path.to_string_lossy().into_owned()
}
