package dev.tablegrip.core.ddl

import dev.tablegrip.core.dialect.SqlDialect
import dev.tablegrip.core.metadata.ForeignKeyInfo
import dev.tablegrip.core.metadata.IndexInfo
import dev.tablegrip.core.metadata.Namespace
import dev.tablegrip.core.metadata.TableRef
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

class DdlGeneratorTest {
    private val app = Namespace(null, "app")
    private val users =
        TableDesign(
            table = TableRef(app, "users"),
            columns =
                listOf(
                    DesignColumn("id", "bigint", nullable = false, autoIncrement = true, originalName = "id"),
                    DesignColumn("email", "varchar(100)", nullable = false, originalName = "email"),
                    DesignColumn("team_id", "integer", originalName = "team_id"),
                    DesignColumn("status", "text", defaultValue = "'active'", originalName = "status"),
                ),
            primaryKey = listOf("id"),
            indexes = listOf(IndexInfo("users_email", listOf("email"), unique = true)),
            foreignKeys = listOf(ForeignKeyInfo("users_team_fk", listOf("team_id"), TableRef(app, "teams"), listOf("id"), onDelete = "SET NULL")),
            primaryKeyName = "users_pkey",
        )

    private fun script(dialect: SqlDialect, original: TableDesign?, target: TableDesign?) = DdlGenerator(dialect).script(TableChange(original, target))

    @Test
    fun `creates a PostgreSQL table with identity, keys after every table exists`() {
        val script = script(SqlDialect.PostgreSQL, null, users.copy(columns = users.columns.map { it.copy(originalName = null) }))
        assertEquals(
            """
            CREATE TABLE "app"."users" (
                "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
                "email" varchar(100) NOT NULL,
                "team_id" integer,
                "status" text DEFAULT 'active',
                CONSTRAINT "users_pkey" PRIMARY KEY ("id")
            );

            CREATE UNIQUE INDEX "users_email" ON "app"."users" ("email");

            ALTER TABLE "app"."users" ADD CONSTRAINT "users_team_fk" FOREIGN KEY ("team_id") REFERENCES "app"."teams" ("id") ON DELETE SET NULL;
            """.trimIndent(),
            script.text,
        )
        assertTrue(script.transactional)
    }

    @Test
    fun `alters PostgreSQL columns in place, renames first`() {
        val target =
            users.copy(
                columns =
                    listOf(
                        users.columns[0],
                        users.columns[1].copy(name = "email_address", type = "varchar(255)"),
                        users.columns[2].copy(nullable = false),
                        users.columns[3].copy(defaultValue = null),
                        DesignColumn("created_at", "timestamptz", nullable = false, defaultValue = "now()"),
                    ),
                indexes = listOf(IndexInfo("users_email", listOf("email_address"), unique = true)),
            )
        val script = script(SqlDialect.PostgreSQL, users, target)
        assertEquals(
            listOf(
                """ALTER TABLE "app"."users" RENAME COLUMN "email" TO "email_address"""",
                """ALTER TABLE "app"."users" ALTER COLUMN "email_address" TYPE varchar(255) USING "email_address"::varchar(255)""",
                """ALTER TABLE "app"."users" ALTER COLUMN "team_id" SET NOT NULL""",
                """ALTER TABLE "app"."users" ALTER COLUMN "status" DROP DEFAULT""",
                """ALTER TABLE "app"."users" ADD COLUMN "created_at" timestamptz DEFAULT now() NOT NULL""",
            ),
            script.statements.map { it.sql },
            "the index follows the renamed column, so it isn't recreated",
        )
        assertTrue(script.warnings.any { "team_id becomes NOT NULL" in it })
    }

    @Test
    fun `MySQL restates whole columns and drops foreign keys by their own syntax`() {
        val dialect = SqlDialect.MySQL
        val mysqlUsers = users.copy(table = TableRef(Namespace("shop", null), "users"), primaryKeyName = "PRIMARY")
        val target =
            mysqlUsers.copy(
                columns = listOf(mysqlUsers.columns[0], mysqlUsers.columns[1].copy(name = "mail"), mysqlUsers.columns[2], mysqlUsers.columns[3].copy(type = "varchar(20)")),
                indexes = listOf(IndexInfo("users_email", listOf("mail"), unique = true)),
                foreignKeys = emptyList(),
            )
        assertEquals(
            listOf(
                "ALTER TABLE `shop`.`users` DROP FOREIGN KEY `users_team_fk`",
                "ALTER TABLE `shop`.`users` CHANGE COLUMN `email` `mail` varchar(100) NOT NULL",
                "ALTER TABLE `shop`.`users` MODIFY COLUMN `status` varchar(20) DEFAULT 'active' NULL",
            ),
            script(dialect, mysqlUsers, target).statements.map { it.sql },
        )
    }

    @Test
    fun `SQL Server renames with sp_rename and names its primary key`() {
        val dialect = SqlDialect.SqlServer
        val dbo = users.copy(table = TableRef(Namespace(null, "dbo"), "users"), primaryKeyName = "PK__users__3213E83F")
        val target = dbo.copy(table = dbo.table.copy(name = "people"), columns = dbo.columns + DesignColumn("age", "int"))
        assertEquals(
            listOf(
                "EXEC sp_rename 'dbo.users', 'people'",
                "ALTER TABLE [dbo].[people] ADD [age] int NULL",
            ),
            script(dialect, dbo, target).statements.map { it.sql },
        )
    }

    @Test
    fun `SQLite adds plain columns in place but rebuilds for anything else`() {
        val dialect = SqlDialect.SQLite
        val main = Namespace(null, null)
        val original =
            TableDesign(
                TableRef(main, "notes"),
                listOf(
                    DesignColumn("id", "INTEGER", nullable = false, autoIncrement = true, originalName = "id"),
                    DesignColumn("body", "TEXT", originalName = "body"),
                ),
                primaryKey = listOf("id"),
                indexes = listOf(IndexInfo("notes_body", listOf("body"), unique = false)),
            )
        val added = script(dialect, original, original.copy(columns = original.columns + DesignColumn("tag", "TEXT")))
        assertEquals(listOf("""ALTER TABLE "notes" ADD COLUMN "tag" TEXT"""), added.statements.map { it.sql })

        val changed = script(dialect, original, original.copy(columns = listOf(original.columns[0], original.columns[1].copy(name = "text", nullable = false))))
        assertEquals(
            listOf(
                "PRAGMA foreign_keys = OFF",
                "CREATE TABLE \"_notes_new\" (\n    \"id\" INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL,\n    \"text\" TEXT NOT NULL\n)",
                """INSERT INTO "_notes_new" ("id", "text") SELECT "id", "body" FROM "notes"""",
                """DROP TABLE "notes"""",
                """ALTER TABLE "_notes_new" RENAME TO "notes"""",
                """CREATE INDEX "notes_body" ON "notes" ("body")""",
                "PRAGMA foreign_keys = ON",
            ),
            changed.statements.map { it.sql },
        )
        assertTrue(changed.warnings.any { "rebuilt" in it })
    }

    @Test
    fun `ClickHouse creates MergeTree tables with nullable types`() {
        val table = TableDesign(TableRef(Namespace("default", null), "events"), listOf(DesignColumn("id", "UInt64", nullable = false), DesignColumn("name", "String")), primaryKey = listOf("id"))
        assertEquals(
            "CREATE TABLE `default`.`events` (\n    `id` UInt64,\n    `name` Nullable(String)\n)\nENGINE = MergeTree\nORDER BY (`id`)",
            script(SqlDialect.ClickHouse, null, table).statements.single().sql,
        )
    }

    @Test
    fun `normalizes types and defaults so aliases aren't differences`() {
        assertEquals(ColumnTypes.normalize("character varying(20)"), ColumnTypes.normalize("VARCHAR( 20 )"))
        assertEquals(ColumnTypes.normalize("int4"), ColumnTypes.normalize("INTEGER"))
        assertEquals(ColumnTypes.normalize("numeric(10, 2)"), ColumnTypes.normalize("decimal(10,2)"))
        assertEquals(ColumnTypes.normalizeDefault("'draft'::character varying"), ColumnTypes.normalizeDefault("'draft'"))
        assertEquals(ColumnTypes.normalizeDefault("(now())"), ColumnTypes.normalizeDefault("NOW()"))
    }
}
