CREATE EXTENSION IF NOT EXISTS btree_gist;
CREATE SCHEMA shop;
CREATE TABLE shop.customers (id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY, email varchar(120) NOT NULL UNIQUE, name text);
CREATE TABLE shop.orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  customer_id integer NOT NULL REFERENCES shop.customers(id) ON DELETE CASCADE ON UPDATE SET NULL,
  total numeric(10,2) NOT NULL DEFAULT 0,
  qty int NOT NULL DEFAULT 1,
  total_with_tax numeric GENERATED ALWAYS AS (total * 1.1) STORED,
  status text NOT NULL DEFAULT 'new',
  during tsrange,
  CONSTRAINT orders_pk PRIMARY KEY (id),
  CONSTRAINT positive_total CHECK (total >= 0),
  CONSTRAINT no_overlap EXCLUDE USING gist (customer_id WITH =, during WITH &&)
);
CREATE INDEX orders_status ON shop.orders (status) WHERE status <> 'done';
CREATE INDEX orders_lower ON shop.orders (lower(status));
COMMENT ON TABLE shop.orders IS 'Customer''s orders';
COMMENT ON COLUMN shop.orders.total IS 'Gross total';
CREATE FUNCTION shop.touch() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END $$;
CREATE TRIGGER orders_touch BEFORE INSERT OR UPDATE ON shop.orders FOR EACH ROW EXECUTE FUNCTION shop.touch();
CREATE TRIGGER orders_audit AFTER DELETE ON shop.orders FOR EACH STATEMENT EXECUTE FUNCTION shop.touch();
ALTER TABLE shop.orders DISABLE TRIGGER orders_audit;
CREATE VIEW shop.big_orders AS SELECT id, total FROM shop.orders WHERE total > 100;
CREATE MATERIALIZED VIEW shop.totals AS SELECT customer_id, sum(total) AS s FROM shop.orders GROUP BY customer_id;
CREATE TABLE shop.events (id int, at date NOT NULL) PARTITION BY RANGE (at);
CREATE TABLE "Mixed Case" ("Id" int PRIMARY KEY, "a""b" text);
CREATE FUNCTION shop.order_total(customer integer) RETURNS numeric LANGUAGE sql STABLE AS $$ SELECT coalesce(sum(total), 0) FROM shop.orders WHERE customer_id = customer $$;
CREATE FUNCTION shop.order_total(customer integer, since date) RETURNS numeric LANGUAGE sql AS $$ SELECT 0::numeric $$;
COMMENT ON FUNCTION shop.order_total(integer) IS 'Sum of a customer''s orders';
CREATE PROCEDURE shop.close_orders(customer integer) LANGUAGE plpgsql AS $$ BEGIN UPDATE shop.orders SET status = 'done' WHERE customer_id = customer; END $$;
