package dev.tablegrip.core.agent

import dev.tablegrip.core.TableGripPaths
import java.nio.file.Path
import java.nio.file.StandardCopyOption.ATOMIC_MOVE
import java.nio.file.StandardCopyOption.REPLACE_EXISTING
import kotlin.io.path.createDirectories
import kotlin.io.path.deleteIfExists
import kotlin.io.path.exists
import kotlin.io.path.listDirectoryEntries
import kotlin.io.path.moveTo
import kotlin.io.path.readText
import kotlin.io.path.writeText
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json

/** An agent chat as it is kept between launches: what the chat showed, and what the agent was sent. */
@Serializable
data class SavedChat(
    val id: String,
    val title: String,
    val createdAt: Long,
    val updatedAt: Long,
    /** The agent last answering in it, by [AgentDescriptor.id]; only shown, the agent picked in the chat answers. */
    val agent: String? = null,
    val messages: List<SavedChatMessage> = emptyList(),
)

@Serializable
data class SavedChatMessage(
    val role: AgentMessage.Role,
    val text: String,
    /** A one-line note sent on the user's behalf rather than a message they typed. */
    val note: Boolean = false,
    val label: String? = null,
    val reasoning: String = "",
    val thoughtSeconds: Int? = null,
    val activities: List<SavedActivity> = emptyList(),
    val error: String? = null,
    /** Mentions by their stand-in character in [text] (see [MentionText]). */
    val mentions: Map<String, SavedMention> = emptyMap(),
    /** Answered run requests, by the index of their code block. */
    val runs: List<SavedRun> = emptyList(),
    /** For a note: the index of the message holding the run request it answers, and that request's block. */
    val origin: Int? = null,
    val originBlock: Int? = null,
)

@Serializable
data class SavedActivity(val id: String, val label: String, val state: AgentEvent.Activity.State)

/** A mention as it was sent: what it read as, and what the agent read for it. */
@Serializable
data class SavedMention(val label: String, val context: String)

@Serializable
data class SavedRun(val block: Int, val state: State, val summary: String? = null) {
    enum class State { Done, Declined, Refused, NotShared }
}

/** What the chat list shows of a [SavedChat], without its messages. */
@Serializable
data class ChatSummary(val id: String, val title: String, val updatedAt: Long, val agent: String? = null)

/**
 * Agent chats, one JSON file each, so a broken file costs one chat and the list is the directory. A missing or unreadable
 * file is skipped, never an error.
 */
class ChatStore(private val directory: Path = TableGripPaths.chats) {
    private val json = Json {
        ignoreUnknownKeys = true
        encodeDefaults = false
    }

    /** Most recently updated first. */
    fun list(): List<ChatSummary> {
        if (!directory.exists()) return emptyList()
        return directory.listDirectoryEntries("*.json")
            .mapNotNull { file -> runCatching { json.decodeFromString<ChatSummary>(file.readText()) }.getOrNull() }
            .sortedByDescending { it.updatedAt }
    }

    fun load(id: String): SavedChat? = runCatching { file(id).takeIf { it.exists() }?.let { json.decodeFromString<SavedChat>(it.readText()) } }.getOrNull()

    /** Writes to a temporary file first, so a crash mid-write leaves the previous version intact. */
    fun save(chat: SavedChat) {
        directory.createDirectories()
        val file = file(chat.id)
        val temp = file.resolveSibling(file.fileName.toString() + ".tmp")
        temp.writeText(json.encodeToString(chat))
        runCatching { temp.moveTo(file, ATOMIC_MOVE, REPLACE_EXISTING) }.getOrElse { temp.moveTo(file, REPLACE_EXISTING) }
    }

    fun rename(id: String, title: String) {
        val chat = load(id) ?: return
        save(chat.copy(title = title))
    }

    fun delete(id: String) {
        file(id).deleteIfExists()
    }

    /** Ids are generated by the app, but a file name is never taken from one unchecked. */
    private fun file(id: String): Path {
        require(id.isNotEmpty() && id.all { it.isLetterOrDigit() || it == '-' }) { "Bad chat id: $id" }
        return directory.resolve("$id.json")
    }
}
