//! Registers every file in `src/specimens/` as a specimen, so adding one never edits a shared file: each file is a
//! module with `pub fn specimen() -> Specimen`.

use std::fmt::Write;
use std::path::PathBuf;

fn main() {
    let dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("src/specimens");
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut files: Vec<PathBuf> = std::fs::read_dir(&dir)
        .unwrap()
        .map(|e| e.unwrap().path())
        .filter(|p| p.extension().is_some_and(|e| e == "rs"))
        .collect();
    files.sort();
    let mut out = String::from("// Generated by build.rs from src/specimens/.\n\n");
    let mut names = Vec::new();
    for file in &files {
        println!("cargo:rerun-if-changed={}", file.display());
        let module = file
            .file_stem()
            .unwrap()
            .to_string_lossy()
            .replace('-', "_");
        writeln!(out, "#[path = {:?}]\nmod {module};", file.to_string_lossy()).unwrap();
        names.push(module);
    }
    out.push_str("\n/// Every specimen, by name.\npub fn all() -> Vec<crate::Specimen> {\n    let mut all = vec![\n");
    for name in &names {
        writeln!(out, "        {name}::specimen(),").unwrap();
    }
    out.push_str("    ];\n    all.sort_by_key(|s| s.name);\n    all\n}\n");
    std::fs::write(
        PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("specimens.rs"),
        out,
    )
    .unwrap();
}
